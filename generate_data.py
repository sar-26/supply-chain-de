"""Phase 1 - synthetic supply-chain data generator (Indian quick-commerce).

Fills the SOURCE (OLTP) tables defined in schema.sql. Relationships are kept
consistent, money fields are plausible, and demand rises around festival
windows and weekends. Identity PKs are GENERATED BY DEFAULT, so we assign our
own ids here to keep foreign keys easy to wire.

Run order: create the schema first (schema.sql), then `python generate_data.py`.
Tune the CONFIG block to grow or shrink the dataset.
"""
import random
from datetime import datetime, timedelta

from faker import Faker

from db import get_connection

fake = Faker("en_IN")
random.seed(42)
Faker.seed(42)

# ----------------------------------------------------------------------
# CONFIG - adjust volumes here (defaults stay well within the 20 GB free tier)
# ----------------------------------------------------------------------
N_PRODUCTS = 300
N_CUSTOMERS = 2000
N_SUPPLIERS = 25
N_DARK_STORES = 30
START_DATE = datetime(2026, 1, 1)
DAYS = 120
AVG_ORDERS_PER_DAY = 150
BATCH = 1000

# ----------------------------------------------------------------------
# Reference data
# ----------------------------------------------------------------------
# (city, state, region) - metros get warehouses; all get dark stores.
CITIES = [
    ("Mumbai", "Maharashtra", "West"), ("Pune", "Maharashtra", "West"),
    ("Ahmedabad", "Gujarat", "West"), ("Delhi", "Delhi", "North"),
    ("Jaipur", "Rajasthan", "North"), ("Lucknow", "Uttar Pradesh", "North"),
    ("Bengaluru", "Karnataka", "South"), ("Hyderabad", "Telangana", "South"),
    ("Chennai", "Tamil Nadu", "South"), ("Kochi", "Kerala", "South"),
    ("Kolkata", "West Bengal", "East"), ("Patna", "Bihar", "East"),
]
WAREHOUSE_CITIES = ["Mumbai", "Delhi", "Bengaluru", "Kolkata"]

# category -> (price range, cost fraction of price)
CATEGORIES = {
    "Fruits & Vegetables": (20, 200, 0.75),
    "Dairy": (25, 300, 0.80),
    "Snacks": (10, 150, 0.55),
    "Beverages": (20, 250, 0.60),
    "Personal Care": (40, 600, 0.50),
    "Household": (30, 500, 0.55),
    "Grocery Staples": (30, 800, 0.70),
}
CUSTOMER_SEGMENTS = ["New", "Regular", "Premium", "Inactive"]
CARRIERS = ["Delhivery", "Ecom Express", "Shadowfax", "InHouse Fleet", "Porter"]


def festival_multiplier(d: datetime) -> float:
    """Approximate demand lift. Refine the windows with exact dates per year."""
    m, day = d.month, d.day
    if m in (10, 11):            # Dussehra / Diwali season
        return 1.9
    if m == 3 and day <= 20:     # Holi
        return 1.4
    if m == 1 and day <= 15:     # New Year / Sankranti / Pongal
        return 1.3
    if m == 8:                   # Independence Day / Raksha Bandhan sales
        return 1.25
    return 1.0


def weekend_multiplier(d: datetime) -> float:
    return 1.25 if d.weekday() >= 5 else 1.0


# ----------------------------------------------------------------------
# Insert helpers
# ----------------------------------------------------------------------
def insert_many(cur, sql, rows):
    for i in range(0, len(rows), BATCH):
        cur.executemany(sql, rows[i:i + BATCH])


def main():
    conn = get_connection()
    cur = conn.cursor()

    # -- Locations: warehouses + dark stores + supplier sites --------------
    locations = []          # (location_id, type, name, city, state, pincode, lat, lng, capacity)
    warehouses, dark_stores, supplier_locs = [], [], []
    loc_id = 1
    for city, state, region in CITIES:
        if city in WAREHOUSE_CITIES:
            locations.append((loc_id, "WAREHOUSE", f"{city} Mother WH", city, state,
                              fake.postcode(), None, None, random.randint(50000, 120000)))
            warehouses.append((loc_id, region))
            loc_id += 1
    for i in range(N_DARK_STORES):
        city, state, region = random.choice(CITIES)
        locations.append((loc_id, "DARK_STORE", f"{city} DS-{i+1}", city, state,
                          fake.postcode(), None, None, random.randint(2000, 8000)))
        dark_stores.append((loc_id, region))
        loc_id += 1
    for i in range(N_SUPPLIERS):
        city, state, region = random.choice(CITIES)
        locations.append((loc_id, "SUPPLIER", f"Supplier Site {i+1}", city, state,
                          fake.postcode(), None, None, None))
        supplier_locs.append(loc_id)
        loc_id += 1

    insert_many(cur,
        """INSERT INTO location
           (location_id, location_type, location_name, city, state, pincode, latitude, longitude, capacity)
           VALUES (:1,:2,:3,:4,:5,:6,:7,:8,:9)""", locations)

    # -- Suppliers ---------------------------------------------------------
    suppliers = [(i + 1, fake.company(), supplier_locs[i], random.randint(2, 21))
                 for i in range(N_SUPPLIERS)]
    insert_many(cur,
        "INSERT INTO supplier (supplier_id, supplier_name, location_id, lead_time_days) VALUES (:1,:2,:3,:4)",
        suppliers)

    # -- Products ----------------------------------------------------------
    products = []           # (product_id, sku, name, category, subcategory, price, cost)
    cat_names = list(CATEGORIES)
    for pid in range(1, N_PRODUCTS + 1):
        cat = random.choice(cat_names)
        lo, hi, cost_frac = CATEGORIES[cat]
        price = round(random.uniform(lo, hi), 2)
        cost = round(price * random.uniform(cost_frac - 0.05, cost_frac + 0.05), 2)
        products.append((pid, f"SKU{pid:05d}", fake.word().title() + f" {cat.split()[0]}",
                         cat, None, price, cost))
    insert_many(cur,
        """INSERT INTO product (product_id, sku, product_name, category, subcategory, unit_price, standard_cost)
           VALUES (:1,:2,:3,:4,:5,:6,:7)""", products)
    product_price = {p[0]: (p[5], p[6]) for p in products}   # id -> (price, cost)

    # -- Customers ---------------------------------------------------------
    customers = []
    for cid in range(1, N_CUSTOMERS + 1):
        city, state, _ = random.choice(CITIES)
        customers.append((cid, fake.name(), city, state, fake.postcode(),
                          random.choice(CUSTOMER_SEGMENTS)))
    insert_many(cur,
        "INSERT INTO customer (customer_id, full_name, city, state, pincode, segment) VALUES (:1,:2,:3,:4,:5,:6)",
        customers)

    conn.commit()

    # -- Transactional data over the date range ---------------------------
    ds_ids = [d[0] for d in dark_stores]
    wh_ids = [w[0] for w in warehouses]

    orders, items, movements, shipments = [], [], [], []
    replenishments, purchase_orders, po_items = [], [], []
    order_id = item_id = move_id = ship_id = replen_id = po_id = po_item_id = 1

    for day_offset in range(DAYS):
        d = START_DATE + timedelta(days=day_offset)
        n_orders = int(AVG_ORDERS_PER_DAY * festival_multiplier(d) * weekend_multiplier(d)
                       * random.uniform(0.8, 1.2))

        for _ in range(n_orders):
            cust = random.randint(1, N_CUSTOMERS)
            ds = random.choice(ds_ids)
            order_ts = d + timedelta(hours=random.randint(6, 23), minutes=random.randint(0, 59))
            orders.append((order_id, cust, ds, order_ts, "APP", "DELIVERED"))

            for _ in range(random.randint(1, 5)):
                pid = random.randint(1, N_PRODUCTS)
                price, cost = product_price[pid]
                qty = random.randint(1, 4)
                gross = round(price * qty, 2)
                discount = round(gross * random.choice([0, 0, 0, 0.05, 0.10]), 2)
                tax = round((gross - discount) * random.choice([0.05, 0.12, 0.18]), 2)
                items.append((item_id, order_id, pid, qty, price, discount, tax))
                item_id += 1
                # sale depletes stock at the dark store
                movements.append((move_id, pid, ds, "SALE", -qty, order_ts, order_id))
                move_id += 1

            # shipment for the order
            dispatch = order_ts + timedelta(minutes=random.randint(10, 60))
            delivered = dispatch + timedelta(minutes=random.randint(15, 120))
            shipments.append((ship_id, order_id, random.choice(CARRIERS),
                              round(random.uniform(15, 80), 2), dispatch, delivered, "DELIVERED"))
            ship_id += 1
            order_id += 1

        # Daily replenishment: warehouse -> dark store (a sample of SKUs)
        for ds in random.sample(ds_ids, k=max(1, len(ds_ids) // 3)):
            wh = random.choice(wh_ids)
            pid = random.randint(1, N_PRODUCTS)
            qty = random.randint(50, 300)
            created = d + timedelta(hours=random.randint(0, 6))
            replenishments.append((replen_id, pid, wh, ds, qty, "RECEIVED", created))
            replen_id += 1
            movements.append((move_id, pid, wh, "TRANSFER", -qty, created, replen_id)); move_id += 1
            movements.append((move_id, pid, ds, "TRANSFER", qty, created, replen_id)); move_id += 1

        # Every ~7 days: procurement supplier -> warehouse
        if day_offset % 7 == 0:
            for wh in wh_ids:
                sup = random.randint(1, N_SUPPLIERS)
                po_ts = d + timedelta(hours=random.randint(0, 5))
                purchase_orders.append((po_id, sup, wh, po_ts,
                                        po_ts + timedelta(days=random.randint(2, 10)), "RECEIVED"))
                for _ in range(random.randint(3, 8)):
                    pid = random.randint(1, N_PRODUCTS)
                    _, cost = product_price[pid]
                    qty = random.randint(100, 500)
                    po_items.append((po_item_id, po_id, pid, qty, cost))
                    po_item_id += 1
                    movements.append((move_id, pid, wh, "INBOUND", qty, po_ts, po_id)); move_id += 1
                po_id += 1

    # -- Bulk insert transactional data -----------------------------------
    insert_many(cur,
        "INSERT INTO sales_order (order_id, customer_id, dark_store_id, order_ts, channel, status) VALUES (:1,:2,:3,:4,:5,:6)",
        orders)
    insert_many(cur,
        "INSERT INTO order_item (order_item_id, order_id, product_id, quantity, unit_price, discount_amt, tax_amt) VALUES (:1,:2,:3,:4,:5,:6,:7)",
        items)
    insert_many(cur,
        "INSERT INTO inventory_movement (movement_id, product_id, location_id, move_type, quantity, move_ts, ref_id) VALUES (:1,:2,:3,:4,:5,:6,:7)",
        movements)
    insert_many(cur,
        "INSERT INTO shipment (shipment_id, order_id, carrier, freight_cost, dispatch_ts, delivered_ts, status) VALUES (:1,:2,:3,:4,:5,:6,:7)",
        shipments)
    insert_many(cur,
        "INSERT INTO replenishment (replen_id, product_id, from_location_id, to_location_id, quantity, status, created_ts) VALUES (:1,:2,:3,:4,:5,:6,:7)",
        replenishments)
    insert_many(cur,
        "INSERT INTO purchase_order (po_id, supplier_id, to_location_id, order_ts, expected_ts, status) VALUES (:1,:2,:3,:4,:5,:6)",
        purchase_orders)
    insert_many(cur,
        "INSERT INTO purchase_order_item (po_item_id, po_id, product_id, quantity, unit_cost) VALUES (:1,:2,:3,:4,:5)",
        po_items)

    conn.commit()

    print(f"Locations:      {len(locations)}")
    print(f"Suppliers:      {len(suppliers)}")
    print(f"Products:       {len(products)}")
    print(f"Customers:      {len(customers)}")
    print(f"Orders:         {len(orders)}")
    print(f"Order items:    {len(items)}")
    print(f"Movements:      {len(movements)}")
    print(f"Shipments:      {len(shipments)}")
    print(f"Replenishments: {len(replenishments)}")
    print(f"Purchase orders:{len(purchase_orders)}")
    print(f"PO items:       {len(po_items)}")

    cur.close()
    conn.close()
    print("Done.")


if __name__ == "__main__":
    main()
