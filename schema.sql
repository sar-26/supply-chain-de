-- ============================================================
-- Supply Chain Data Platform — SOURCE (OLTP) schema (Oracle)
-- These are the ONLY tables created by hand. The analytics
-- layer (dim_* / fact_* / dq_issues / snapshots) is built
-- entirely by dbt — never create those manually.
-- Runs on Oracle Autonomous Database or Oracle XE.
-- ============================================================

CREATE TABLE product (
  product_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku            VARCHAR2(40)  NOT NULL UNIQUE,
  product_name   VARCHAR2(200) NOT NULL,
  category       VARCHAR2(80),
  subcategory    VARCHAR2(80),
  unit_price     NUMBER(12,2)  NOT NULL,
  standard_cost  NUMBER(12,2)  NOT NULL,
  created_at     TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE location (
  location_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_type  VARCHAR2(20) NOT NULL
                 CHECK (location_type IN ('WAREHOUSE','DARK_STORE','SUPPLIER')),
  location_name  VARCHAR2(200),
  city           VARCHAR2(80),
  state          VARCHAR2(80),
  pincode        VARCHAR2(10),
  latitude       NUMBER(9,6),
  longitude      NUMBER(9,6),
  capacity       NUMBER
);

CREATE TABLE customer (
  customer_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name      VARCHAR2(200),
  city           VARCHAR2(80),
  state          VARCHAR2(80),
  pincode        VARCHAR2(10),
  segment        VARCHAR2(40),
  registered_at  TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE supplier (
  supplier_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_name  VARCHAR2(200) NOT NULL,
  location_id    NUMBER REFERENCES location(location_id),
  lead_time_days NUMBER,
  created_at     TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE sales_order (
  order_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id    NUMBER NOT NULL REFERENCES customer(customer_id),
  dark_store_id  NUMBER REFERENCES location(location_id),
  order_ts       TIMESTAMP NOT NULL,
  channel        VARCHAR2(20),
  status         VARCHAR2(20)
                 CHECK (status IN ('PLACED','PICKED','SHIPPED','DELIVERED','CANCELLED'))
);

CREATE TABLE order_item (
  order_item_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id       NUMBER NOT NULL REFERENCES sales_order(order_id),
  product_id     NUMBER NOT NULL REFERENCES product(product_id),
  quantity       NUMBER NOT NULL,
  unit_price     NUMBER(12,2) NOT NULL,
  discount_amt   NUMBER(12,2) DEFAULT 0,
  tax_amt        NUMBER(12,2) DEFAULT 0
);

CREATE TABLE inventory_movement (
  movement_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id     NUMBER NOT NULL REFERENCES product(product_id),
  location_id    NUMBER NOT NULL REFERENCES location(location_id),
  move_type      VARCHAR2(20) NOT NULL
                 CHECK (move_type IN ('INBOUND','SALE','TRANSFER','ADJUSTMENT')),
  quantity       NUMBER NOT NULL,
  move_ts        TIMESTAMP NOT NULL,
  ref_id         NUMBER
);

CREATE TABLE replenishment (
  replen_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id       NUMBER NOT NULL REFERENCES product(product_id),
  from_location_id NUMBER NOT NULL REFERENCES location(location_id),
  to_location_id   NUMBER NOT NULL REFERENCES location(location_id),
  quantity         NUMBER NOT NULL,
  status           VARCHAR2(20)
                   CHECK (status IN ('REQUESTED','APPROVED','IN_TRANSIT','RECEIVED','CANCELLED')),
  created_ts       TIMESTAMP NOT NULL
);

CREATE TABLE shipment (
  shipment_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id       NUMBER REFERENCES sales_order(order_id),
  carrier        VARCHAR2(80),
  freight_cost   NUMBER(12,2),
  dispatch_ts    TIMESTAMP,
  delivered_ts   TIMESTAMP,
  status         VARCHAR2(20)
);

CREATE TABLE purchase_order (
  po_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_id    NUMBER NOT NULL REFERENCES supplier(supplier_id),
  to_location_id NUMBER NOT NULL REFERENCES location(location_id),
  order_ts       TIMESTAMP NOT NULL,
  expected_ts    TIMESTAMP,
  status         VARCHAR2(20)
                 CHECK (status IN ('OPEN','PARTIAL','RECEIVED','CANCELLED'))
);

CREATE TABLE purchase_order_item (
  po_item_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  po_id          NUMBER NOT NULL REFERENCES purchase_order(po_id),
  product_id     NUMBER NOT NULL REFERENCES product(product_id),
  quantity       NUMBER NOT NULL,
  unit_cost      NUMBER(12,2) NOT NULL
);
